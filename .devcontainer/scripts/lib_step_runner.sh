#!/usr/bin/env bash
# Shared helper: run an init step without letting its failure abort the
# caller, while making failures impossible to miss. Source this file; do not
# execute it directly.
#
# Rationale: a hard failure partway through container setup can otherwise
# leave the devcontainer without a usable terminal to debug from, if the
# caller runs under `set -e` and is itself invoked from `postStartCommand`
# with `"waitFor": "postStartCommand"` -- the first failing step aborts the
# whole init script, which aborts postStartCommand, which blocks the editor
# from ever attaching. See docs/features/devcontainer-init-resilience/.

INIT_WARNINGS_LOG="${INIT_WARNINGS_LOG:-/home/vscode/services/log/init_warnings.log}"

_step_runner_big_banner() {
  local title="$1"
  local detail="$2"
  {
    echo ""
    echo "########################################################################"
    echo "##  WARNING: ${title}"
    echo "########################################################################"
    echo "${detail}"
    echo "########################################################################"
    echo ""
  } >&2
}

# run_step <description> <command> [args...]
# Runs <command>; on non-zero exit, logs a big warning and the command's
# output to INIT_WARNINGS_LOG, but always returns 0 so the caller continues.
#
# Contract for <command>: if it wants a warning to be guaranteed-visible
# through this mechanism, it must exit non-zero. Logging to stderr while
# still exiting 0 is NOT surfaced here -- run_step only inspects the exit
# code, so a step that wants "this is worth a human's attention" must signal
# it via its own exit status, not just by printing.
run_step() {
  local description="$1"
  shift
  local output
  local rc=0
  output="$("$@" 2>&1)" || rc=$?
  if [[ ${rc} -ne 0 ]]; then
    _step_runner_big_banner "init step failed: ${description}" "command: $*
exit code: ${rc}
output:
${output}"
    mkdir -p "$(dirname "${INIT_WARNINGS_LOG}")"
    {
      echo "[$(date '+%Y-%m-%d %H:%M:%S')] FAILED: ${description} (exit ${rc})"
      echo "  command: $*"
      echo "${output}" | sed 's/^/  | /'
      echo ""
    } >> "${INIT_WARNINGS_LOG}"
  fi
  return 0
}

# init_warnings_reset: call once at the start of init_all.sh so each container
# start begins with a clean slate (stale warnings from a prior start don't
# linger and get confused with the current run's).
init_warnings_reset() {
  mkdir -p "$(dirname "${INIT_WARNINGS_LOG}")"
  : > "${INIT_WARNINGS_LOG}"
}

# init_warnings_summary: call once at the end of init_all.sh. Prints a final
# banner if any step failed, and best-effort forces the warnings log into
# view in the attached editor window (no-op if no window is attached yet,
# e.g. during the very first container creation).
init_warnings_summary() {
  [[ -s "${INIT_WARNINGS_LOG}" ]] || return 0
  local failed_count
  failed_count="$(grep -c '^\[.*\] FAILED:' "${INIT_WARNINGS_LOG}" 2>/dev/null || echo '?')"
  _step_runner_big_banner "init_all.sh finished with ${failed_count} failed step(s)" \
"The devcontainer started anyway so you have a working terminal to debug from.
Full details: ${INIT_WARNINGS_LOG}
Quick view:   cat ${INIT_WARNINGS_LOG}"
  _step_runner_try_editor_popup
}

# init_warnings_install_shell_banner: idempotently drop a snippet into the
# system-wide bash/zsh rc files so ANY new interactive terminal -- not just
# whoever was watching the container's startup log -- immediately shows a
# banner if the last init_all.sh run left warnings behind. Targets the
# system-wide rc files (not ~/.bashrc / ~/.zshrc) because those can be
# regenerated by devcontainer features on rebuild; /etc/bash.bashrc and
# /etc/zsh/zshrc are not.
init_warnings_install_shell_banner() {
  local marker="# --- init_warnings_banner (managed by lib_step_runner.sh) ---"
  local snippet
  snippet=$(cat <<EOF
${marker}
if [ -s "${INIT_WARNINGS_LOG}" ]; then
  echo ""
  echo "########################################################################"
  echo "##  devcontainer startup had warnings -- see:"
  echo "##  cat ${INIT_WARNINGS_LOG}"
  echo "########################################################################"
  echo ""
fi
${marker}
EOF
)
  local rc_file
  for rc_file in /etc/bash.bashrc /etc/zsh/zshrc; do
    [[ -f "${rc_file}" ]] || continue
    if grep -qF "${marker}" "${rc_file}" 2>/dev/null; then
      continue
    fi
    printf '\n%s\n' "${snippet}" | sudo tee -a "${rc_file}" >/dev/null
  done
}

_step_runner_try_editor_popup() {
  local editor_cli=""
  local candidate
  for candidate in codium code; do
    if command -v "${candidate}" >/dev/null 2>&1; then
      editor_cli="${candidate}"
      break
    fi
  done
  [[ -n "${editor_cli}" ]] || return 0
  [[ -n "${VSCODE_IPC_HOOK_CLI:-}" ]] || return 0
  "${editor_cli}" --reuse-window --goto "${INIT_WARNINGS_LOG}:1:1" >/dev/null 2>&1 || true
}
